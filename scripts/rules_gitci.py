"""Проекция enforce на git-хуки и CI (ADR-0005): .githooks / .pre-commit-config.yaml и .github/workflows.

Инструменты копируются в .angainor/tools/ проекта и зависят только от стандартной библиотеки.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from rules_lib import Effective, Registry

GIT_EVENTS = ("pre-commit", "commit-msg", "pre-push")
CI_EVENT = "ci"
TOOLS_DIR = ".angainor/tools"
MARK = "generated by angainor"
PC_BEGIN = "  # angainor:begin"
PC_END = "  # angainor:end"
SH_ARG1 = '"$1"'
PR_RANGE = "origin/${{ github.base_ref }}..HEAD"


def split_enforce(effective: list[Effective]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    git, ci = [], []
    for e in effective:
        for item in e.rule.enforce:
            if item["event"] in GIT_EVENTS:
                git.append(item)
            elif item["event"] == CI_EVENT:
                ci.append(item)
    return git, ci


def _args(item: dict[str, Any], project: str, *, arg1: str, pr_range: str = PR_RANGE) -> str:
    out = []
    for a in item.get("args", []):
        out.append(a.replace("{project}", project).replace("{arg1}", arg1).replace("{pr_range}", pr_range))
    return " ".join(out)


def _vendor(reg: Registry, items: list[dict[str, Any]], repo_dir: Path, version: str) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for item in items:
        name = Path(item["tool"]).name
        src = (reg.root / item["tool"]).read_text(encoding="utf-8").replace("\r\n", "\n")
        files[repo_dir / TOOLS_DIR / name] = f"# {MARK} {version} from {item['tool']} — не править\n{src}"
    return files


def _githooks(items: list[dict[str, Any]], project: str, repo_dir: Path, version: str) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for event in GIT_EVENTS:
        cmds = [f"python {TOOLS_DIR}/{Path(i['tool']).name} {_args(i, project, arg1=SH_ARG1)}".rstrip()
                for i in items if i["event"] == event]
        if cmds:
            files[repo_dir / ".githooks" / event] = f"#!/bin/sh\n# {MARK} {version} — не править\nset -e\n" + "\n".join(cmds) + "\n"
    return files


def _precommit_block(items: list[dict[str, Any]], project: str, version: str) -> str:
    lines = [f"{PC_BEGIN} — {MARK} {version}, не править", "  - repo: local", "    hooks:"]
    for i, item in enumerate(items):
        name = Path(item["tool"]).stem
        raw = " ".join(a.replace("{project}", project) for a in item.get("args", []) if a != "{arg1}")
        pass_files = "{arg1}" in item.get("args", [])
        lines += [
            f"      - id: angainor-{item['event']}-{name}",
            f"        name: angainor {name} ({item['event']})",
            "        language: system",
            f"        entry: python {TOOLS_DIR}/{Path(item['tool']).name}" + (f" {raw}" if raw else ""),
            f"        stages: [{item['event']}]",
            f"        pass_filenames: {'true' if pass_files else 'false'}",
        ]
    lines.append(PC_END)
    return "\n".join(lines) + "\n"


def apply_precommit(existing: str | None, block: str | None) -> str | None:
    """Вставляет/заменяет/убирает блок между метками angainor. None — файл менять не нужно."""
    text = existing.replace("\r\n", "\n") if existing is not None else None
    if text is not None and PC_BEGIN in text and PC_END in text:
        pre, rest = text.split(PC_BEGIN, 1)
        _, post = rest.split(PC_END, 1)
        post = post[1:] if post.startswith("\n") else post
        return pre + (block or "") + post
    if block is None:
        return None
    return (text.rstrip("\n") + "\n\n" if text else "repos:\n") + block


def _workflows(items: list[dict[str, Any]], project: str, repo_dir: Path, version: str) -> dict[Path, str]:
    stages: dict[str, list[dict[str, Any]]] = {}
    for item in items:
        stages.setdefault(item["stage"], []).append(item)
    files: dict[Path, str] = {}
    for stage, group in stages.items():
        triggers = sorted({i.get("when", "pull_request") for i in group})
        lines = [f"# {MARK} {version} — не править", f"name: angainor-{stage}", "on:"]
        for t in triggers:
            lines += ["  pull_request:"] if t == "pull_request" else ["  push:", "    branches: [main, master]"]
        lines += ["jobs:", f"  {stage}:", "    runs-on: ubuntu-latest", "    steps:",
                  "      - uses: actions/checkout@v5", "        with:", "          fetch-depth: 0",
                  "      - uses: actions/setup-python@v6", "        with:", "          python-version: '3.12'"]
        for i in group:
            name = Path(i["tool"]).name
            args = _args(i, project, arg1="")
            lines += [f"      - name: {Path(name).stem}", f"        if: github.event_name == '{i.get('when', 'pull_request')}'",
                      f"        run: python {TOOLS_DIR}/{name}" + (f" {args}" if args else "")]
        files[repo_dir / ".github" / "workflows" / f"angainor-{stage}.yml"] = "\n".join(lines) + "\n"
    return files


def gitci_files(reg: Registry, effective: list[Effective], project: str, repo_dir: Path,
                version: str, mode: str) -> tuple[dict[Path, str], list[str]]:
    git, ci = split_enforce(effective)
    files: dict[Path, str] = {}
    errors: list[str] = []
    files.update(_vendor(reg, git + ci, repo_dir, version))
    files.update(_workflows(ci, project, repo_dir, version))
    if mode == "pre-commit":
        pc = repo_dir / ".pre-commit-config.yaml"
        new = apply_precommit(pc.read_text(encoding="utf-8") if pc.exists() else None,
                              _precommit_block(git, project, version) if git else None)
        if new is not None:
            files[pc] = new
    else:
        files.update(_githooks(git, project, repo_dir, version))
    for path in files:
        if path.exists() and path.parent.name in (".githooks", "workflows") and MARK not in path.read_text(encoding="utf-8"):
            errors.append(f"{path}: файл существует и не сгенерирован Angainor — переименуйте или удалите его")
    return files, errors


def stale_gitci(repo_dir: Path, keep: set[Path]) -> list[Path]:
    out: list[Path] = []
    for d, pattern in ((repo_dir / TOOLS_DIR, "*.py"), (repo_dir / ".github" / "workflows", "angainor-*.yml"),
                       (repo_dir / ".githooks", "*")):
        if d.is_dir():
            for p in sorted(d.glob(pattern)):
                if p.is_file() and p not in keep and (d.name != ".githooks" or MARK in p.read_text(encoding="utf-8")):
                    out.append(p)
    return out

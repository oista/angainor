#!/usr/bin/env python3
"""Сборка проекций реестра правил (ADR-0003).

    python scripts/build_rules.py                 # страницы реестра: RULE-INDEX, RULE-MATRIX, RULES.md проектов
    python scripts/build_rules.py --projections   # + файлы в репозиториях проектов (.cursor/rules, AGENTS.md)
    python scripts/build_rules.py --check         # ничего не пишет; код 1, если файлы расходятся с реестром
    python scripts/build_rules.py --diff          # показать расхождения
    --project prodata                             # только один проект
    --repos-root PATH                             # где лежат репозитории проектов (по умолчанию — рядом с angainor)

Не созданы: .cursor/hooks.json (правила с исполняемой частью — следующая итерация).
"""

from __future__ import annotations

import argparse
import difflib
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rules_gitci import CI_EVENT, GIT_EVENTS, gitci_files, stale_gitci  # noqa: E402
from rules_lib import ROOT, Effective, Registry, estimate_tokens, load_registry, resolve  # noqa: E402

BEGIN = "<!-- angainor:begin -->"
END = "<!-- angainor:end -->"
MODE_SYMBOL = {"always": "●", "globs": "◐", "on_request": "○"}


def header(version: str, project: str) -> str:
    return f"generated by angainor {version} from angainor/rules (проект {project}) — не править"


def active(eff: list[Effective]) -> list[Effective]:
    return [e for e in eff if e.enabled]


def render_core(eff: list[Effective], version: str, project: str) -> str:
    always = [e for e in active(eff) if e.activation == "always"]
    lines = ["---", f"description: Angainor — обязательные правила проекта {project}", "alwaysApply: true", "---", "",
             f"<!-- {header(version, project)} -->", ""]
    for e in always:
        lines += [f"## {e.rule.id} {e.rule.title}", "", e.text, ""]
    return "\n".join(lines).rstrip() + "\n"


def render_rule_mdc(e: Effective, version: str, project: str) -> str:
    r = e.rule
    fm = ["---"]
    if e.activation == "globs":
        fm += [f"description: {r.id} {r.title}", f"globs: {', '.join(e.globs)}", "alwaysApply: false"]
    else:
        phrases = ", ".join(f"«{t}»" for t in r.triggers)
        fm += [f"description: {r.id} {r.title}. Применять, когда пользователь говорит: {phrases}", "alwaysApply: false"]
    fm += ["---", "", f"<!-- {header(version, project)} -->", "", f"# {r.id} {r.title}", "", e.text, ""]
    return "\n".join(fm)


def render_agents_block(project: str, eff: list[Effective], env: dict | None, version: str) -> str:
    on = active(eff)
    out = [BEGIN, f"<!-- {header(version, project)} между метками -->", "", "## Правила Angainor", ""]
    always = [e for e in on if e.activation == "always"]
    if always:
        out += ["### Всегда", ""]
        for e in always:
            out += [f"**{e.rule.id} {e.rule.title}.**", "", e.text, ""]
    rest = [e for e in on if e.activation != "always"]
    if rest:
        out += ["### Остальные правила", "", "| Правило | Когда действует |", "| --- | --- |"]
        for e in rest:
            when = ("файлы: " + ", ".join(f"`{g}`" for g in e.globs)) if e.activation == "globs" else \
                   ("по запросу: " + ", ".join(f"«{t}»" for t in e.rule.triggers))
            out.append(f"| {e.rule.id} {e.rule.title} | {when} |")
        out.append("")
    if env:
        out += ["### Окружение", ""]
        for name, cmd in (env.get("commands") or {}).items():
            out.append(f"- `{name}`: `{cmd}`")
        for c in env.get("constraints") or []:
            out.append(f"- Ограничение: {c}")
        out.append("")
    out.append(END)
    return "\n".join(out) + "\n"


def apply_block(existing: str | None, block: str) -> str:
    if existing is None:
        return "# Агентам\n\n" + block
    existing = existing.replace("\r\n", "\n")
    if BEGIN in existing and END in existing:
        pre, rest = existing.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + block.rstrip("\n") + post
    return existing.rstrip("\n") + "\n\n" + block


def project_files(reg: Registry, project: str, repo_dir: Path) -> tuple[dict[Path, str], list[str]]:
    eff, errors = resolve(reg, project)
    prof = reg.profiles[project]
    version = prof["angainor"]["version"]
    files: dict[Path, str] = {}
    rules_dir = repo_dir / ".cursor" / "rules"
    if any(e.enabled and e.activation == "always" for e in eff):
        files[rules_dir / "angainor-core.mdc"] = render_core(eff, version, project)
    for e in active(eff):
        if e.activation != "always":
            files[rules_dir / f"angainor-{e.rule.id}.mdc"] = render_rule_mdc(e, version, project)
    agent_rules = [e for e in active(eff)]
    files.update(hook_files(reg, agent_rules, project, repo_dir, version))
    extra, extra_errors = gitci_files(reg, agent_rules, project, repo_dir, version, prof.get("git_hooks", "githooks"))
    files.update(extra)
    errors += extra_errors
    agents = repo_dir / "AGENTS.md"
    existing = agents.read_text(encoding="utf-8") if agents.exists() else None
    files[agents] = apply_block(existing, render_agents_block(project, eff, prof.get("environment"), version))
    return files, errors


HOOKS_DIR = ".cursor/hooks/angainor"


def hook_files(reg: Registry, effective: list[Effective], project: str, repo_dir: Path, version: str) -> dict[Path, str]:
    """Проекция enforce: копии инструментов в .cursor/hooks/angainor/ и записи в .cursor/hooks.json.

    Чужие записи hooks.json сохраняются; наши (команда содержит HOOKS_DIR) пересобираются и идут первыми.
    """
    files: dict[Path, str] = {}
    plan_prefix = reg.profiles[project].get("plan_prefix", project)
    ours: dict[str, list[dict[str, Any]]] = {}
    for e in effective:
        for item in e.rule.enforce:
            if item["event"] in GIT_EVENTS or item["event"] == CI_EVENT:
                continue
            name = Path(item["tool"]).name
            src = (reg.root / item["tool"]).read_text(encoding="utf-8").replace("\r\n", "\n")
            files[repo_dir / HOOKS_DIR / name] = f"# generated by angainor {version} from {item['tool']} — не править\n{src}"
            args = " ".join(a.replace("{project}", project).replace("{plan_prefix}", plan_prefix) for a in item.get("args", []))
            entry: dict[str, Any] = {"command": f"python {HOOKS_DIR}/{name}" + (f" {args}" if args else "")}
            if item.get("matcher"):
                entry["matcher"] = item["matcher"]
            entry["timeout"] = item.get("timeout", 15)
            if item.get("fail") == "closed":
                entry["failClosed"] = True
            ours.setdefault(item["event"], []).append(entry)

    hooks_path = repo_dir / ".cursor" / "hooks.json"
    existing: dict[str, Any] | None = None
    if hooks_path.exists():
        try:
            existing = json.loads(hooks_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            existing = None
    if not ours and existing is None:
        return files
    doc = existing if isinstance(existing, dict) else {"version": 1}
    doc.setdefault("version", 1)
    hooks = doc.setdefault("hooks", {})
    for event in list(hooks):
        hooks[event] = [h for h in hooks[event] if HOOKS_DIR not in h.get("command", "")]
    for event, entries in ours.items():
        hooks[event] = entries + hooks.get(event, [])
    doc["hooks"] = {k: v for k, v in hooks.items() if v}
    files[hooks_path] = json.dumps(doc, ensure_ascii=False, indent=2) + "\n"
    return files


def stale_generated(repo_dir: Path, keep: set[Path]) -> list[Path]:
    """Сгенерированные ранее файлы (angainor-*.mdc и копии хуков), которых больше нет в реестре."""
    out: list[Path] = []
    for d, pattern in ((repo_dir / ".cursor" / "rules", "angainor-*.mdc"), (repo_dir / HOOKS_DIR, "*.py")):
        if d.is_dir():
            out += [p for p in sorted(d.glob(pattern)) if p not in keep]
    return out + stale_gitci(repo_dir, keep)


# ---- страницы реестра ----

def render_index(reg: Registry) -> str:
    lines = ["# Реестр правил — индекс", "", "<!-- generated by scripts/build_rules.py — не править -->", "",
             "| ID | Название | Статус | Область | Режим | Проверка | Норма |", "| --- | --- | --- | --- | --- | --- | --- |"]
    if not reg.rules:
        return "\n".join(lines[:4]) + "\nПравил пока нет.\n"
    for rid in sorted(reg.rules):
        r = reg.rules[rid]
        chk = f"`{r.check}`" if r.check else "пожелание"
        lines.append(f"| [{r.id}](../{r.path}) | {r.title} | {r.status} | {r.scope} | {MODE_SYMBOL[r.activation]} {r.activation} | {chk} | {', '.join(r.norm) or '—'} |")
    return "\n".join(lines) + "\n"


def render_matrix(reg: Registry) -> str:
    projects = sorted(reg.profiles)
    if not projects or not reg.rules:
        return "# Реестр правил — матрица\n\n<!-- generated by scripts/build_rules.py — не править -->\n\nПравил и проектов пока нет.\n"
    lines = ["# Реестр правил — матрица", "", "<!-- generated by scripts/build_rules.py — не править -->", "",
             "Обозначения: ● всегда · ◐ по файлам · ○ по запросу · ✕ выключено · – не подключено · · не применимо.", "",
             "| Правило | " + " | ".join(projects) + " |", "| --- | " + " | ".join("---" for _ in projects) + " |"]
    resolved = {p: {e.rule.id: e for e in resolve(reg, p)[0]} for p in projects}
    for rid in sorted(reg.rules):
        r = reg.rules[rid]
        cells = []
        for p in projects:
            if r.scope.startswith("project:") and r.scope != f"project:{p}":
                cells.append("·")
            elif rid not in resolved[p]:
                cells.append("–")
            else:
                e = resolved[p][rid]
                cells.append(MODE_SYMBOL[e.activation] if e.enabled else "✕")
        lines.append(f"| {rid} {r.title} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def render_project_page(reg: Registry, project: str) -> str:
    eff, _ = resolve(reg, project)
    prof = reg.profiles[project]
    version = prof["angainor"]["version"]
    always_text = render_core(eff, version, project) if any(e.enabled and e.activation == "always" for e in eff) else ""
    tokens = estimate_tokens(always_text)
    budget = prof["always_on_budget_tokens"]
    lines = [f"# {project} — действующие правила", "", "<!-- generated by scripts/build_rules.py — не править -->", "",
             f"Версия Angainor: {version}. Всегда в контексте: ≈{tokens} токенов из {budget}.", ""]
    for title, mode in (("Всегда", "always"), ("По файлам", "globs"), ("По запросу", "on_request")):
        items = [e for e in eff if e.enabled and e.activation == mode]
        if items:
            lines += [f"## {title}", ""]
            for e in items:
                extra = ", ".join(e.globs) if mode == "globs" else ", ".join(f"«{t}»" for t in e.rule.triggers) if mode == "on_request" else ""
                lines.append(f"- {e.rule.id} {e.rule.title}" + (f" — {extra}" if extra else ""))
            lines.append("")
    off = [e for e in eff if not e.enabled]
    if off:
        lines += ["## Выключено", ""]
        for e in off:
            lines.append(f"- {e.rule.id} {e.rule.title} — {e.reason}" + (f" ({e.waiver})" if e.waiver else ""))
        lines.append("")
    wish = [e for e in eff if e.enabled and not e.rule.check]
    if wish:
        lines += ["## Без проверки (пожелания)", ""] + [f"- {e.rule.id} {e.rule.title}" for e in wish] + [""]
    return "\n".join(lines).rstrip() + "\n"


def registry_pages(reg: Registry) -> dict[Path, str]:
    base = reg.root / "rules"
    pages = {base / "RULE-INDEX.md": render_index(reg), base / "RULE-MATRIX.md": render_matrix(reg)}
    for p in reg.profiles:
        pages[base / "projects" / p / "RULES.md"] = render_project_page(reg, p)
    return pages


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--projections", action="store_true", help="писать файлы в репозитории проектов")
    ap.add_argument("--check", action="store_true", help="не писать; код 1 при расхождении")
    ap.add_argument("--diff", action="store_true", help="показать расхождения")
    ap.add_argument("--project")
    ap.add_argument("--repos-root", type=Path)
    ap.add_argument("--root", type=Path, default=ROOT)
    args = ap.parse_args(argv)

    reg = load_registry(args.root)
    if reg.errors:
        print("Реестр содержит ошибки (запустите scripts/check_rules.py):", file=sys.stderr)
        for e in reg.errors:
            print(f"  {e}", file=sys.stderr)
        return 1
    repos_root = args.repos_root or args.root.parent

    wanted: dict[Path, str] = dict(registry_pages(reg))
    removed: list[Path] = []
    problems: list[str] = []
    check_projections = args.projections or args.check or args.diff
    if check_projections:
        for project, prof in reg.profiles.items():
            if args.project and project != args.project:
                continue
            repo_dir = repos_root / prof["repo"]
            if not repo_dir.is_dir():
                print(f"предупреждение: репозиторий {repo_dir} не найден, проекции {project} пропущены", file=sys.stderr)
                continue
            files, errs = project_files(reg, project, repo_dir)
            problems += errs
            wanted.update(files)
            removed += stale_generated(repo_dir, set(files))
    if problems:
        for e in problems:
            print(f"  {e}", file=sys.stderr)
        return 1

    changed: list[Path] = []
    for path, content in wanted.items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != content:
            changed.append(path)
            if args.diff:
                diff = difflib.unified_diff((current or "").splitlines(), content.splitlines(), str(path), "generated", lineterm="")
                print("\n".join(diff))
    changed_total = len(changed) + len(removed)

    if args.check or args.diff:
        for p in removed:
            print(f"лишний сгенерированный файл: {p}", file=sys.stderr)
        for p in changed:
            print(f"расходится: {p}", file=sys.stderr)
        print("Проекции совпадают с реестром" if not changed_total else f"Расхождений: {changed_total}")
        return 1 if (args.check and changed_total) else 0

    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(wanted[path], encoding="utf-8", newline="\n")
        print(f"записано: {path}")
    for p in removed:
        print(f"устарел, удалите вручную: {p}")
    print(f"Готово: файлов записано {len(changed)}, без изменений {len(wanted) - len(changed)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
